// Generates engine/trainer-classes.js: each Frontier facility class's in-game
// trainer class name (gFacilityClassToTrainerClass,
// src/data/pokemon/trainer_class_lookups.h -> gTrainerClassNames,
// src/data/text/trainer_class_names.h), title case, as sim/trainer-name.mjs
// reads them -- for the page, which cannot read the decomp.
//   node tools/gen-trainer-classes.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { FRONTIER_TRAINERS } from "../engine/frontier-trainers.js";
import { trainerName } from "../sim/trainer-name.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const out = {};
for (const t of FRONTIER_TRAINERS) {
  const full = trainerName(t.id), name = full.slice(full.length - t.name.length);
  const cls = full.slice(0, full.length - t.name.length - 1);
  if (name.toUpperCase() !== t.name) throw new Error(`trainer ${t.id}: name split failed (${full})`);
  if (out[t.cls] && out[t.cls] !== cls) throw new Error(`class ${t.cls}: two names`);
  out[t.cls] = cls;
}
const body = `// ── trainer-classes.js ─────────────────────────────────────────────────────
// GENERATED by tools/gen-trainer-classes.mjs -- do not hand-edit.
// Frontier facility class -> the trainer class the game shows (title case).
export const TRAINER_CLASS_NAMES = ${JSON.stringify(out, null, 2)};
`;
fs.writeFileSync(path.join(here, "../engine/trainer-classes.js"), body);
console.log(`${Object.keys(out).length} classes`);
